"""
=============================================================================
LOCAL ANOMALY DETECTION MODULE (Module C)
=============================================================================

Executes local, deterministic, unsupervised anomaly detection using scikit-learn
Isolation Forest on entity-level operational telemetry features.

CONSTRAINTS & COMPLIANCE:
-----------------------------------------------------------------------------
1. Purely local execution: scikit-learn, NumPy, and SQLite only.
2. NO deep learning, NO external LLM APIs (OpenAI, Gemini, Groq, etc.).
3. Air-gapped: Zero network requests; zero data leaves the local machine.
4. Deterministic: Fixed random_state=42 for 100% reproducible results.
5. No hardcoding: Operates on arbitrary uploaded datasets across all entities.

MODEL PARAMETERS:
-----------------------------------------------------------------------------
- Algorithm: sklearn.ensemble.IsolationForest
- n_estimators = 150: Number of isolation trees in the forest.
- max_samples = 'auto': Subsampling size (min(256, n_samples)) per tree.
- contamination = 0.15: Proportion of outliers expected in dataset (~15%).
- random_state = 42: Fixed seed guaranteeing identical isolation splits.

INTERPRETATION LIMITATIONS:
-----------------------------------------------------------------------------
1. Small Sample Size Variance (N < 10):
   When the entity count is small, the empirical distribution of path lengths
   has higher variance. Anomaly boundaries should be treated as indicative.
2. Multicollinearity & Scale Sensitivity:
   Heavily skewed metrics (such as unbounded alert volumes) can dominate
   early tree splits. Features are interpreted comparatively against peer means.
3. Unsupervised Mathematical Deviations:
   Isolation Forest flags statistical distance from the cluster, not intent.
   An anomalous score flags operational divergence that requires domain-level
   evidence drill-down (provided by Modules A, B, D, and E).

FEATURE SPECIFICATION:
-----------------------------------------------------------------------------
1. alert_volume: Total volume of alerts generated by the entity.
2. critical_alert_ratio: Proportion of alerts classified as CRITICAL severity.
3. median_closure_time: Median investigation duration for closed cases (minutes).
4. escalation_rate: Proportion of cases escalated to supervisory tiers.
5. repeat_alert_rate: Ratio of (asset, category) clusters occurring repeatedly.
6. telemetry_coverage: Ratio of monitored assets with active, fresh telemetry.
7. average_investigation_duration: Mean duration of case investigations (minutes).
=============================================================================
"""
import sqlite3
import statistics
import hashlib
import json
import os
from datetime import datetime, timezone
from datetime import datetime, timezone
from typing import Any
import numpy as np
from sklearn.ensemble import IsolationForest

from models import Finding
from config import CONFIG, assessment_reference_timestamp


STALE_TELEMETRY_DAYS = float(CONFIG["assessment"]["telemetry_stale_days"]["CRITICAL"])
MODEL_RANDOM_STATE = int(CONFIG["anomaly"]["random_state"])
MODEL_CONTAMINATION = float(CONFIG["anomaly"]["contamination"])
MODEL_N_ESTIMATORS = int(CONFIG["anomaly"]["n_estimators"])

FEATURE_NAMES = [
    "alert_volume",
    "critical_alert_ratio",
    "median_closure_time",
    "escalation_rate",
    "repeat_alert_rate",
    "telemetry_coverage",
    "average_investigation_duration",
]


def _parse_iso(ts: str | None) -> datetime | None:
    if not ts or not isinstance(ts, str) or ts.strip() == "":
        return None
    try:
        s = ts.strip().rstrip("Z")
        if "+" in s:
            s = s[:s.index("+")]
        return datetime.fromisoformat(s).replace(tzinfo=timezone.utc)
    except ValueError:
        return None


def extract_entity_features(db_path: str) -> dict[str, dict[str, float]]:
    """
    Construct deterministic entity-level features from the database.
    Operates strictly from raw database tables — zero hardcoded metrics.
    """
    conn = sqlite3.connect(db_path)
    conn.row_factory = sqlite3.Row
    cur = conn.cursor()
    now = datetime.fromisoformat(assessment_reference_timestamp().replace("Z", "+00:00"))

    cur.execute("SELECT entity_id FROM entities ORDER BY entity_id")
    entity_ids = [r["entity_id"] for r in cur.fetchall()]

    features: dict[str, dict[str, float]] = {}

    for eid in entity_ids:
        # 1. Alert volume
        cur.execute("SELECT COUNT(*) as cnt FROM alerts WHERE entity_id = ?", (eid,))
        alert_volume = float(cur.fetchone()["cnt"])

        # 2. Critical alert ratio
        cur.execute(
            "SELECT COUNT(*) as cnt FROM alerts WHERE entity_id = ? AND severity = 'CRITICAL'",
            (eid,),
        )
        critical_count = cur.fetchone()["cnt"]
        critical_ratio = float(critical_count / alert_volume) if alert_volume > 0 else 0.0

        # 3. Escalation rate (among closed cases)
        cur.execute(
            """
            SELECT COUNT(*) as total, SUM(escalated) as esc
            FROM cases
            WHERE entity_id = ?
            """,
            (eid,),
        )
        row = cur.fetchone()
        total_cases = row["total"] or 0
        esc_cases = row["esc"] or 0
        escalation_rate = float(esc_cases / total_cases) if total_cases > 0 else 0.0

        # 4 & 7. Median closure time & average investigation duration
        cur.execute(
            "SELECT investigation_duration FROM cases WHERE entity_id = ? AND investigation_duration IS NOT NULL",
            (eid,),
        )
        durations = [float(r["investigation_duration"]) for r in cur.fetchall()]
        median_closure_time = float(statistics.median(durations)) if durations else 0.0
        avg_investigation_duration = float(statistics.mean(durations)) if durations else 0.0

        # 5. Repeat alert rate: fraction of (asset, category) groups seen > once
        cur.execute(
            """
            SELECT COUNT(*) as total_groups,
                   SUM(CASE WHEN cnt > 1 THEN 1 ELSE 0 END) as repeated_groups
            FROM (
                SELECT asset_id, category, COUNT(*) as cnt
                FROM alerts
                WHERE entity_id = ?
                GROUP BY asset_id, category
            )
            """,
            (eid,),
        )
        rrow = cur.fetchone()
        total_groups = rrow["total_groups"] or 0
        repeated_groups = rrow["repeated_groups"] or 0
        repeat_alert_rate = float(repeated_groups / total_groups) if total_groups > 0 else 0.0

        # 6. Telemetry coverage: fraction of assets with fresh telemetry (<= 7 days)
        cur.execute(
            "SELECT asset_id, last_telemetry FROM assets WHERE entity_id = ?",
            (eid,),
        )
        asset_rows = cur.fetchall()
        total_assets = len(asset_rows)
        fresh_assets = 0
        for ar in asset_rows:
            last = _parse_iso(ar["last_telemetry"])
            if last and (now - last).total_seconds() / 86400.0 <= STALE_TELEMETRY_DAYS:
                fresh_assets += 1
        telemetry_coverage = float(fresh_assets / total_assets) if total_assets > 0 else 0.0

        features[eid] = {
            "alert_volume": alert_volume,
            "critical_alert_ratio": round(critical_ratio, 4),
            "median_closure_time": round(median_closure_time, 2),
            "escalation_rate": round(escalation_rate, 4),
            "repeat_alert_rate": round(repeat_alert_rate, 4),
            "telemetry_coverage": round(telemetry_coverage, 4),
            "average_investigation_duration": round(avg_investigation_duration, 2),
            # Backwards-compatible aliases for existing tests
            "median_investigation_duration": round(median_closure_time, 2),
            "avg_investigation_duration": round(avg_investigation_duration, 2),
        }

    conn.close()
    return features



def isolation_forest_tree_path_attribution(clf, X, feature_names):
    """
    Computes a formal local feature attribution by traversing the constituent 
    DecisionTrees of the IsolationForest. Features that isolate the sample 
    early (near the root, lower depth) receive higher attribution weight.
    """
    attributions = []
    for i in range(X.shape[0]):
        sample = X[i].reshape(1, -1)
        feat_scores = {f: 0.0 for f in feature_names}
        
        for tree in clf.estimators_:
            node = 0
            depth = 1.0
            tree_obj = tree.tree_
            
            while tree_obj.children_left[node] != tree_obj.children_right[node]:
                feature_index = tree_obj.feature[node]
                feat_name = feature_names[feature_index]
                
                # Weight by 1/depth so early splits matter more
                feat_scores[feat_name] += 1.0 / depth
                
                threshold = tree_obj.threshold[node]
                if sample[0, feature_index] <= threshold:
                    node = tree_obj.children_left[node]
                else:
                    node = tree_obj.children_right[node]
                depth += 1.0
                
        # Normalize scores to sum to 1.0
        total = sum(feat_scores.values())
        if total > 0:
            for f in feat_scores:
                feat_scores[f] = round(feat_scores[f] / total, 4)
                
        attributions.append(feat_scores)
    return attributions

def evaluate_entity_anomalies(
    db_path: str,
    contamination: float = MODEL_CONTAMINATION,
    random_state: int = MODEL_RANDOM_STATE,
) -> dict[str, dict[str, Any]]:
    """
    Run Isolation Forest on extracted entity features and evaluate every entity.
    Returns per-entity anomaly profiles including classification, score, and explanation.
    """
    entity_features = extract_entity_features(db_path)
    if len(entity_features) < int(CONFIG["anomaly"]["minimum_entities"]):
        return {}

    entity_ids = sorted(entity_features.keys())
    X = np.array(
        [[entity_features[eid][f] for f in FEATURE_NAMES] for eid in entity_ids],
        dtype=float,
    )

    clf = IsolationForest(
        n_estimators=MODEL_N_ESTIMATORS,
        max_samples="auto",
        contamination=contamination,
        random_state=random_state,
    )
    clf.fit(X)

    # Model Lifecycle & Versioning
    model_timestamp = datetime.now(timezone.utc).isoformat()
    training_data_identity = hashlib.sha256(str(entity_ids).encode()).hexdigest()[:12]
    model_version_id = f"IForest-v1.0-{training_data_identity}"
    
    model_metadata = {
        "model_name": "sat_sa_isolation_forest",
        "algorithm": "sklearn.ensemble.IsolationForest",
        "version": "1.0",
        "model_id": model_version_id,
        "feature_schema": {
            "version": "1.0",
            "features": FEATURE_NAMES
        },
        "parameters": {
            "n_estimators": MODEL_N_ESTIMATORS,
            "max_samples": "auto",
            "contamination": contamination,
            "random_state": random_state
        },
        "training_dataset_identity": training_data_identity,
        "creation_timestamp": model_timestamp,
        "code_config_version": "PS-157-Final"
    }
    
    metadata_path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "model_metadata.json")
    with open(metadata_path, "w") as f:
        json.dump(model_metadata, f, indent=2)

    raw_scores = clf.score_samples(X)  # lower = more anomalous
    predictions = clf.predict(X)       # -1 = anomaly, 1 = normal

    # Normalise scores to 0.0 - 1.0 (1.0 = most anomalous)
    min_s, max_s = float(raw_scores.min()), float(raw_scores.max())
    if max_s > min_s:
        normalised = 1.0 - (raw_scores - min_s) / (max_s - min_s)
    else:
        normalised = np.zeros(len(raw_scores))

    peer_means = {
        f: float(np.mean([entity_features[e][f] for e in entity_ids]))
        for f in FEATURE_NAMES
    }

    # Generate formal tree path attributions for all samples
    local_attributions = isolation_forest_tree_path_attribution(clf, X, FEATURE_NAMES)

    results: dict[str, dict[str, Any]] = {}

    for i, eid in enumerate(entity_ids):
        feats = entity_features[eid]
        score = float(normalised[i])
        raw_score = float(raw_scores[i])
        is_anom = bool(predictions[i] == -1)

        # Peer means excluding the entity itself for cleaner deviation measurement
        peer_means_ex = {
            f: float(np.mean([entity_features[e][f] for e in entity_ids if e != eid]))
            for f in FEATURE_NAMES
        }
        deviations = {
            f: round(feats[f] - peer_means_ex[f], 4)
            for f in FEATURE_NAMES
        }

        # Build formal model-derived explanation
        attr = local_attributions[i]
        sorted_attr = sorted(attr.items(), key=lambda kv: kv[1], reverse=True)
        top_features = sorted_attr[:3]
        
        explanation_parts = []
        feature_attributions_list = []
        rank = 1
        
        for feat_name, weight in top_features:
            dev = deviations[feat_name]
            direction = "above" if dev > 0 else "below"
            explanation_parts.append(
                f"{feat_name}={feats[feat_name]:.3f} (Tree isolating weight: {weight*100:.1f}%)"
            )
            feature_attributions_list.append({
                "feature": feat_name,
                "value": feats[feat_name],
                "attribution": weight,
                "rank": rank
            })
            rank += 1
            
        explanation = f"Top isolating features (Formal Tree Path Attribution): {'; '.join(explanation_parts)}"

        results[eid] = {
            "entity_id": eid,
            "anomaly_score": round(score, 4),
            "anomaly_score_raw": round(raw_score, 6),
            "anomaly_classification": "ANOMALY" if is_anom else "NORMAL",
            "is_anomaly": is_anom,
            "model_version_id": model_version_id,
            "feature_values": {f: feats[f] for f in FEATURE_NAMES},
            "peer_means": {f: round(peer_means[f], 4) for f in FEATURE_NAMES},
            "feature_deviations": deviations,
            "explanation": explanation,
            "attribution_method": "isolation_forest_tree_path_attribution",
            "attribution_limitation": "Attribution based on inverse depth of splits in IsolationForest trees. Explains isolation mathematically.",
            "feature_attributions": feature_attributions_list
        }

    return results


def detect_anomalies(db_path: str) -> list[Finding]:
    """
    Run Isolation Forest against the database and generate formal
    supervisory findings for classified anomalous entities.
    """
    profiles = evaluate_entity_anomalies(db_path)
    findings: list[Finding] = []

    conn = sqlite3.connect(db_path)
    cur = conn.cursor()

    for eid, prof in sorted(profiles.items()):
        if not prof["is_anomaly"]:
            continue

        score = prof["anomaly_score"]
        raw_score = prof["anomaly_score_raw"]
        severity = "HIGH" if score >= 0.70 else "MEDIUM"

        cur.execute("SELECT alert_id FROM alerts WHERE entity_id = ? ORDER BY timestamp DESC LIMIT 5", (eid,))
        ev_alerts = [r[0] for r in cur.fetchall()]
        cur.execute("SELECT case_id FROM cases WHERE entity_id = ? ORDER BY opened_at DESC LIMIT 5", (eid,))
        ev_cases = [r[0] for r in cur.fetchall()]
        cur.execute("SELECT asset_id FROM assets WHERE entity_id = ? LIMIT 5", (eid,))
        ev_assets = [r[0] for r in cur.fetchall()]
        evidence_ids = ev_alerts + ev_cases + ev_assets

        findings.append(Finding(
            finding_id=f"ANOM-{eid}",
            entity_id=eid,
            finding_type="ANOMALY",
            severity=severity,
            title="Statistical Anomaly Detected via Isolation Forest",
            rationale=(
                f"Entity classified as anomalous by Isolation Forest (normalised score: {score:.3f}). "
                f"{prof['explanation']}. This entity exhibits systemic behavioural departure from peer norms."
            ),
            evidence_ids=evidence_ids,
            supporting_metrics={
                "anomaly_score_normalised": score,
                "anomaly_score_raw": raw_score,
                "anomaly_classification": prof["anomaly_classification"],
                  "model_version_id": prof.get("model_version_id"),
                "feature_values": prof["feature_values"],
                "peer_means": prof["peer_means"],
                "feature_deviations": prof["feature_deviations"],
                "explanation": prof["explanation"],
                "feature_attributions": prof.get("feature_attributions", []),
                "attribution_method": prof["attribution_method"],
                "attribution_limitation": prof["attribution_limitation"],
                "model_parameters": {
                    "algorithm": "IsolationForest",
                    "n_estimators": MODEL_N_ESTIMATORS,
                    "contamination": MODEL_CONTAMINATION,
                    "random_state": MODEL_RANDOM_STATE,
                },
            },
        ))

    conn.close()
    return findings


def get_entity_features(db_path: str) -> dict[str, dict]:
    """Public accessor for feature extraction (reused by pipeline.py and tests)."""
    return extract_entity_features(db_path)
